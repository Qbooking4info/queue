// Payment receipt as a branded PDF. Built on-device from the payment row (so it works
// offline once the visit has loaded), then handed to the share sheet, where the patient
// can save it to Files/Drive, print it, or send it on WhatsApp.
import * as Print from 'expo-print'
import * as Sharing from 'expo-sharing'
import { supabase } from './supabase'

export interface ReceiptPayment {
  amount: number
  platform_fee: number | null
  paystack_ref: string | null
  method: string | null
  paid_at: string | null
  status: string
}

export async function getPaymentForAppointment(appointmentId: string): Promise<ReceiptPayment | null> {
  const { data } = await supabase.from('payments')
    .select('amount, platform_fee, paystack_ref, method, paid_at, status')
    .eq('appointment_id', appointmentId).eq('status', 'success')
    .order('paid_at', { ascending: false }).limit(1).maybeSingle()
  return (data as ReceiptPayment | null) ?? null
}

const naira = (n: number) => '₦' + Math.round(n).toLocaleString('en-NG')
const esc = (s: unknown) => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]!))

const MARK = `<svg width="44" height="44" viewBox="0 0 72 72"><rect x="24" y="4" width="24" height="64" rx="8" fill="#0F766E"/><rect x="4" y="24" width="64" height="24" rx="8" fill="#14B8A6"/><rect x="24" y="24" width="24" height="24" fill="#134E4A"/><circle cx="36" cy="36" r="6" fill="#FF7A59"/></svg>`

export async function shareReceipt(input: {
  payment: ReceiptPayment
  patientName: string
  patientCode?: string | null
  doctorName?: string | null
  hospitalName?: string | null
  visitDate: string
  visitTime?: string | null
  visitType?: string | null
}) {
  const p = input.payment
  const fee = Number(p.platform_fee ?? 0)
  const consult = Math.max(0, Number(p.amount) - fee)
  const paidAt = p.paid_at ? new Date(p.paid_at).toLocaleString('en-NG', { dateStyle: 'medium', timeStyle: 'short' }) : '—'
  const ref = p.paystack_ref ?? '—'
  const html = `<!doctype html><html><head><meta charset="utf-8"><style>
    body{font-family:-apple-system,Roboto,Helvetica,Arial,sans-serif;color:#0B1B1E;padding:36px;}
    .brand{display:flex;align-items:center;gap:12px;margin-bottom:6px}
    .brand b{font-size:26px;color:#134E4A;letter-spacing:-0.5px}
    .tag{color:#0F766E;font-size:12px;margin:0 0 28px 56px}
    h1{font-size:20px;margin:0 0 4px}.muted{color:#4B5B5E;font-size:13px}
    .paid{display:inline-block;background:#DCFCE7;color:#15803D;font-weight:700;font-size:12px;padding:4px 10px;border-radius:99px;margin-top:8px}
    table{width:100%;border-collapse:collapse;margin-top:22px;font-size:14px}
    td{padding:10px 0;border-bottom:1px solid #E3ECEB}td.r{text-align:right}
    tr.total td{font-weight:800;font-size:16px;border-bottom:none;padding-top:14px}
    .grid{display:grid;grid-template-columns:1fr 1fr;gap:14px;margin-top:22px;font-size:13px}
    .grid div span{display:block;color:#4B5B5E;font-size:11px;text-transform:uppercase;letter-spacing:.6px;margin-bottom:2px}
    .foot{margin-top:36px;color:#4B5B5E;font-size:11px;line-height:1.5}
  </style></head><body>
    <div class="brand">${MARK}<b>Queue</b></div>
    <p class="tag">Better Access. Healthier Tomorrow.</p>
    <h1>Payment receipt</h1>
    <div class="muted">Reference ${esc(ref)}</div>
    <div class="paid">✓ PAID</div>
    <div class="grid">
      <div><span>Patient</span>${esc(input.patientName)}${input.patientCode ? ` · ${esc(input.patientCode)}` : ''}</div>
      <div><span>Paid on</span>${esc(paidAt)}</div>
      <div><span>Doctor</span>${esc(input.doctorName ?? 'To be assigned')}</div>
      <div><span>Hospital</span>${esc(input.hospitalName ?? '—')}</div>
      <div><span>Visit</span>${esc(input.visitDate)}${input.visitTime ? ' · ' + esc(input.visitTime.slice(0, 5)) : ''}${input.visitType ? ' · ' + esc(input.visitType === 'virtual' ? 'Video' : 'In person') : ''}</div>
      <div><span>Paid with</span>${esc(p.method ?? 'Card')} via Paystack</div>
    </div>
    <table>
      <tr><td>Consultation</td><td class="r">${naira(consult)}</td></tr>
      ${fee > 0 ? `<tr><td>Booking fee</td><td class="r">${naira(fee)}</td></tr>` : ''}
      <tr class="total"><td>Total paid</td><td class="r">${naira(Number(p.amount))}</td></tr>
    </table>
    <div class="foot">This receipt was generated by the Queue app. Keep it for your records or HMO claims.
    Questions about this payment? Contact Queue Support in the app and quote the reference above.</div>
  </body></html>`

  const { uri } = await Print.printToFileAsync({ html, base64: false })
  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(uri, { mimeType: 'application/pdf', UTI: 'com.adobe.pdf', dialogTitle: 'Save or share your receipt' })
  } else {
    await Print.printAsync({ uri })
  }
}
